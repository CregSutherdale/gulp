export function materialOf(prop) {
  if (!prop) return 'plastic';
  const own = prop.material || prop.sfx;
  if (own && MATERIALS.includes(own)) return own;
  const id = String(prop.id || '').toLowerCase();
  if (MATERIAL_OF[id]) return MATERIAL_OF[id];
  for (const [re, m] of MATERIAL_RULES) if (re.test(id)) return m;
  return 'plastic';
}
