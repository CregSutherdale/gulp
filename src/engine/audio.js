function comp(c, o) {
  const n = c.createDynamicsCompressor();
  n.threshold.value = o.threshold; n.knee.value = o.knee; n.ratio.value = o.ratio;
  n.attack.value = o.attack; n.release.value = o.release;
  return n;
}
// The Web Audio DynamicsCompressor adds automatic makeup gain: (1 / curve(0 dBFS))^0.6
// (Blink/WebKit DynamicsCompressorKernel). We cancel it so the comps only ever turn
// things DOWN and the gain staging stays exactly as designed.
function makeupGain(o) {
  const lin = (d) => Math.pow(10, d / 20), dbl = (x) => 20 * Math.log10(x);
  const T = o.threshold, K = o.knee, R = o.ratio, lt = lin(T);
  const knee = (x, k) => (x < lt ? x : lt + (1 - Math.exp(-k * (x - lt))) / k);
  const slopeAt = (x, k) => {
    if (x < lt) return 1;
    const x2 = x * 1.001;
    return (dbl(knee(x2, k)) - dbl(knee(x, k))) / (dbl(x2) - dbl(x));
  };
  let lo = 0.1, hi = 10000, k = 5;
  const xk = lin(T + K);
  for (let i = 0; i < 15; i++) { if (slopeAt(xk, k) < 1 / R) hi = k; else lo = k; k = Math.sqrt(lo * hi); }
  const kneeDb = T + K, yKneeDb = dbl(knee(lin(kneeDb), k));
  const full = 1 < lin(kneeDb) ? knee(1, k) : lin(yKneeDb + (0 - kneeDb) / R);
  return Math.pow(1 / full, 0.6);
}
// Equal-power fades as short linear segments (never throws on overlapping automation).
const RAMP_N = 12;
function rampShape(fd, x) { // x in 0..1 at a segment boundary
  return fd.fadeIn ? fd.from + (fd.to - fd.from) * Math.sin(x * Math.PI / 2) : fd.to + (fd.from - fd.to) * Math.cos(x * Math.PI / 2);
}
function rampCurve(p, fd) {
  p.cancelScheduledValues(fd.t0);
  p.setValueAtTime(fd.from, fd.t0);
  for (let i = 1; i <= RAMP_N; i++) p.linearRampToValueAtTime(rampShape(fd, i / RAMP_N), fd.t0 + fd.dur * (i / RAMP_N));
}
// The value a rampCurve has reached at time t (same piecewise-linear shape the browser plays).
function curveValue(fd, t) {
  if (!fd) return 0;
  const x = clamp((t - fd.t0) / fd.dur, 0, 1) * RAMP_N, i = Math.floor(x);
  if (i >= RAMP_N) return rampShape(fd, 1);
  const a = rampShape(fd, i / RAMP_N), b = rampShape(fd, (i + 1) / RAMP_N);
  return a + (b - a) * (x - i);
}
function noiseBuffer(c, pink, rng = Math.random) {
  const n = Math.floor(c.sampleRate * 1.5), b = c.createBuffer(1, n, c.sampleRate), d = b.getChannelData(0);
  let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
  for (let i = 0; i < n; i++) {
    const w = rng() * 2 - 1;
    if (!pink) { d[i] = w; continue; }
    // Paul Kellet's pink filter
    b0 = 0.99886 * b0 + w * 0.0555179; b1 = 0.99332 * b1 + w * 0.0750759; b2 = 0.969 * b2 + w * 0.153852;
    b3 = 0.8665 * b3 + w * 0.3104856; b4 = 0.55 * b4 + w * 0.5329522; b5 = -0.7616 * b5 - w * 0.016898;
    d[i] = (b0 + b1 + b2 + b3 + b4 + b5 + b6 + w * 0.5362) * 0.11; b6 = w * 0.115926;
  }
  return b;
}
// A small, bright room: a few early reflections + a 0.9 s decaying stereo tail whose
// highs die faster (air absorption). Procedural DSP, no recorded impulse.
function roomIR(c, rng = Math.random) {
  const sr = c.sampleRate, len = Math.floor(sr * 0.95), ir = c.createBuffer(2, len, sr);
  const pre = Math.floor(sr * 0.012);
  for (let ch = 0; ch < 2; ch++) {
    const d = ir.getChannelData(ch);
    let lp = 0;
    for (let i = pre; i < len; i++) {
      const tt = (i - pre) / sr;
      const a = Math.exp(-tt * 6.9 / 0.85);              // RT60 about 0.85 s
      const cut = 0.55 * Math.exp(-tt * 3) + 0.05;       // one-pole coefficient falls: darker tail
      lp += cut * ((rng() * 2 - 1) - lp);
      d[i] = lp * a;
    }
    [0.007, 0.011, 0.017, 0.023, 0.031].forEach((s, j) => {
      const i = pre + Math.floor((s + ch * 0.0013 * (j + 1)) * sr);
      if (i < len) d[i] += (j % 2 ? -1 : 1) * 0.5 * Math.pow(0.8, j);
    });
  }
  let e = 0; // normalize energy so the send level means what it says
  for (let ch = 0; ch < 2; ch++) { const d = ir.getChannelData(ch); for (let i = 0; i < len; i++) e += d[i] * d[i]; }
  const s = 1 / Math.sqrt(e / 2);
  for (let ch = 0; ch < 2; ch++) { const d = ir.getChannelData(ch); for (let i = 0; i < len; i++) d[i] *= s * 0.5; }
  return ir;
}
