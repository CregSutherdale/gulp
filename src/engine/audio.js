// ------------------------------------------------------------------ voice
// One sound event: its parts feed `out`; `out` feeds the SFX bus (and the reverb send).
// The engine tracks voices so it can cap and steal them.
class Voice {
  constructor(au, t, { kind = 'sfx', send = 0, pan = 0, gain = 1 } = {}) {
    const c = au.ctx;
    this.au = au; this.t = t; this.end = t; this.kind = kind; this.last = null;
    this.out = c.createGain();
    this.out.gain.value = gain * dbToGain(FADER_DB[kind] || 0); // the sound's mixer fader
    let node = this.out;
    if (pan && c.createStereoPanner) {
      this.pan = c.createStereoPanner(); this.pan.pan.value = pan;
      this.out.connect(this.pan); node = this.pan;
    }
    node.connect(au.sfxIn);
    if (send > 0) {
      this.send = c.createGain(); this.send.gain.value = send;
      node.connect(this.send); this.send.connect(au.verbIn);
    }
    au._register(this);
  }
  hold(src, stopAt) { if (stopAt >= this.end) { this.end = stopAt; this.last = src; } }
  done() { if (this.last) this.last.onended = () => this.free(); }
  free() {
    if (this.dead) return;
    this.dead = true;
    try { this.out.disconnect(); if (this.pan) this.pan.disconnect(); if (this.send) this.send.disconnect(); } catch (e) { /* already gone */ }
  }
  fadeOut(at, tau = 0.012) {
    const g = this.out.gain;
    g.cancelScheduledValues(at); g.setTargetAtTime(0, at, tau);
    this.end = Math.min(this.end, at + tau * 8);
  }
}

// ------------------------------------------------------------------ synthesis parts
// All parts take (au, v, t, opts) and schedule into voice `v` at audio time `t`.
// Envelopes: linear attack `a`, optional `hold`, exponential decay reaching ~-43 dB at `d`.
function env(g, t, a, hold, d, vol) {
  g.gain.setValueAtTime(0, t);
  g.gain.linearRampToValueAtTime(vol, t + a);
  if (hold) g.gain.setValueAtTime(vol, t + a + hold);
  g.gain.setTargetAtTime(0, t + a + (hold || 0), d / 5);
  return t + a + (hold || 0) + d * 1.4 + 0.02;
}
function filt(au, type, f, q, from) {
  const n = au.ctx.createBiquadFilter();
  n.type = type; n.frequency.value = f; n.Q.value = q;
  from.connect(n);
  return n;
}
function osc(au, v, t, o) {
  const c = au.ctx, n = c.createOscillator(), g = c.createGain();
  n.type = o.type || 'sine';
  const fr = n.frequency;
  if (o.f0) { fr.setValueAtTime(o.f0, t); fr.exponentialRampToValueAtTime(o.f, t + (o.glide || 0.04)); } else fr.setValueAtTime(o.f, t);
  if (o.f1) fr.exponentialRampToValueAtTime(o.f1, t + (o.glide || 0.04) + (o.glide2 || 0.1));
  if (o.vib) { // vibrato / wobble LFO, fading in over vib.fade
    const l = c.createOscillator(), lg = c.createGain();
    l.frequency.value = o.vib.rate;
    lg.gain.setValueAtTime(0, t); lg.gain.linearRampToValueAtTime(o.f * o.vib.depth, t + (o.vib.fade || 0.05));
    l.connect(lg); lg.connect(fr); l.start(t); l.stop(t + (o.a || 0.005) + (o.hold || 0) + (o.d || 0.15) * 1.4 + 0.05);
  }
  n.connect(g);
  const stop = env(g, t, o.a ?? 0.004, o.hold, o.d ?? 0.15, o.vol);
  let tail = g;
  if (o.lp) tail = filt(au, 'lowpass', o.lp, o.lpq ?? 0.7, tail);
  if (o.hp) tail = filt(au, 'highpass', o.hp, 0.7, tail);
  tail.connect(o.to || v.out);
  n.start(t); n.stop(stop); v.hold(n, stop);
  return n;
}
function noise(au, v, t, o) {
  const c = au.ctx, s = c.createBufferSource(), g = c.createGain();
  s.buffer = o.pink ? au.pinkBuf : au.noiseBuf; s.loop = true;
  const f = c.createBiquadFilter();
  f.type = o.type || 'bandpass'; f.Q.value = o.q ?? 1;
  f.frequency.setValueAtTime(o.f, t);
  if (o.f1) f.frequency.exponentialRampToValueAtTime(o.f1, t + (o.sweep || o.d || 0.1));
  s.connect(f); f.connect(g);
  const stop = env(g, t, o.a ?? 0.003, o.hold, o.d ?? 0.08, o.vol);
  let tail = g;
  if (o.lp) tail = filt(au, 'lowpass', o.lp, 0.7, tail);
  tail.connect(o.to || v.out);
  s.start(t, au.rnd(0, 0.9)); s.stop(stop); v.hold(s, stop);
  return s;
}
// FM bell: bright strike that mellows as the modulation index decays.
function bell(au, v, t, o) {
  const c = au.ctx, car = c.createOscillator(), mod = c.createOscillator(), mg = c.createGain(), g = c.createGain();
  const ratio = o.ratio || 2.76, d = o.d ?? 0.6;
  car.frequency.value = o.f; mod.frequency.value = o.f * ratio;
  const dev = (o.index ?? 1.2) * o.f * ratio;
  mg.gain.setValueAtTime(dev, t); mg.gain.setTargetAtTime(0, t, (o.idecay ?? d * 0.3) / 4);
  mod.connect(mg); mg.connect(car.frequency);
  car.connect(g);
  const stop = env(g, t, o.a ?? 0.002, o.hold, d, o.vol);
  filt(au, 'lowpass', o.lp || 7500, 0.7, g).connect(o.to || v.out);
  car.start(t); mod.start(t); car.stop(stop); mod.stop(stop); v.hold(car, stop);
}
// Soft pad tone: detuned pair through a lowpass, slow attack. Used under chords.
function pad(au, v, t, o) {
  for (const det of [-6, 6]) {
    const c = au.ctx, n = c.createOscillator(), g = c.createGain();
    n.type = o.type || 'triangle'; n.frequency.value = o.f; n.detune.value = det;
    if (o.f0) { n.frequency.setValueAtTime(o.f0, t); n.frequency.exponentialRampToValueAtTime(o.f, t + (o.glide || 0.3)); }
    n.connect(g);
    const stop = env(g, t, o.a ?? 0.05, o.hold, o.d ?? 0.8, o.vol / 2);
    const lp = filt(au, 'lowpass', o.lp || 2400, 0.6, g);
    if (o.lp0) { lp.frequency.setValueAtTime(o.lp0, t); lp.frequency.exponentialRampToValueAtTime(o.lp || 2400, t + (o.glide || 0.3)); }
    lp.connect(o.to || v.out);
    n.start(t); n.stop(stop); v.hold(n, stop);
  }
}

